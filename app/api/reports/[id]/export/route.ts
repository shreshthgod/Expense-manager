import { z } from "zod";
import { NextResponse } from "next/server";
import { searchParamsObject } from "@/lib/api/response";
import { withAuth } from "@/lib/api/route";
import { ApiError } from "@/lib/api/errors";
import { toCsv, type CsvCell } from "@/lib/utils/csv";
import { getReport } from "@/server/services/report.service";

export const runtime = "nodejs";

const exportQuery = z.object({ format: z.enum(["csv", "json"]).default("csv") });

function fileName(title: string, ext: string) {
  return `${title.replace(/[^A-Za-z0-9 _-]/g, "").replace(/\s+/g, "-").toLowerCase() || "report"}.${ext}`;
}

/** Exports the stored (immutable) report dataset. PDF = browser print of the detail page. */
export const GET = withAuth<{ id: string }>(async ({ request, userId, params }) => {
  const { format } = exportQuery.parse(searchParamsObject(request));
  const report = await getReport(userId, params.id);
  if (!report.content) throw ApiError.rule("This report was generated by an older version and has no structured data. Regenerate it to export.", "LEGACY_REPORT");
  const d = report.content.dataset;
  if (format === "json") {
    return new NextResponse(JSON.stringify(report.content, null, 2), {
      headers: {
        "Content-Type": "application/json; charset=utf-8",
        "Content-Disposition": `attachment; filename="${fileName(report.title, "json")}"`,
        "Cache-Control": "no-store",
      },
    });
  }
  const rows: CsvCell[][] = [
    ["Report", report.title, "", ""],
    ["Period", `${d.period.start} to ${d.period.lastDay}`, "", ""],
    ["Currency", d.currency, "", ""],
    ["Generated at", d.generatedAt, "Time zone", d.timezone],
    ["", "", "", ""],
    ["Summary", "Value", "Previous period", "Change %"],
    ["Income", d.totals.income, d.previousTotals.income, d.changes.incomePct],
    ["Gross spending", d.totals.grossExpense, d.previousTotals.grossExpense, null],
    ["Refunds", d.totals.refunds, d.previousTotals.refunds, null],
    ["Net spending", d.totals.netSpending, d.previousTotals.netSpending, d.changes.netSpendingPct],
    ["Surplus", d.totals.surplus, d.previousTotals.surplus, d.changes.surplusPct],
    ["Savings rate %", d.totals.savingsRate ?? "n/a", d.previousTotals.savingsRate ?? "n/a", d.changes.savingsRateDelta],
    ["", "", "", ""],
    ["Category", "Net spending", "Share %", "Previous period"],
    ...d.categories.map((c) => [c.name, c.total, c.percentage, c.previousTotal] as CsvCell[]),
    ["", "", "", ""],
    ["Budget", "Spent", "Limit", "Utilization %"],
    ...d.budgets.map((b) => [b.name, b.spent, b.amount, b.utilization] as CsvCell[]),
    ["", "", "", ""],
    ["Merchant", "Net spending", "Purchases", "Previous period"],
    ...d.merchants.map((m) => [m.merchant, m.total, m.count, m.previousTotal] as CsvCell[]),
  ];
  return new NextResponse(toCsv(["Section", "A", "B", "C"], rows), {
    headers: {
      "Content-Type": "text/csv; charset=utf-8",
      "Content-Disposition": `attachment; filename="${fileName(report.title, "csv")}"`,
      "Cache-Control": "no-store",
    },
  });
});
