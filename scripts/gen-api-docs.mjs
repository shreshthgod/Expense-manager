// Generates docs/API.md from app/api/**/route.ts (methods, auth wrapper, doc comments).
// Usage: node scripts/gen-api-docs.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve("app/api");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else if (name === "route.ts") files.push(full);
  }
})(root);

const groups = new Map();
let count = 0;
for (const file of files.sort()) {
  const src = readFileSync(file, "utf8");
  const route = "/api/" + path.relative(root, path.dirname(file)).split(path.sep).join("/");
  const group = route.split("/")[2];
  for (const m of src.matchAll(/((?:\/\*\*[\s\S]*?\*\/\s*)?)export const (GET|POST|PUT|PATCH|DELETE) = (\w+)/g)) {
    const doc = (m[1] || "")
      .replace(/\/\*\*|\*\//g, "")
      .split("\n")
      .map((l) => l.replace(/^\s*\*\s?/, "").trim())
      .filter(Boolean)
      .join(" ");
    const wrapper = m[3];
    const auth = wrapper === "withPublic" ? "public" : wrapper === "withCron" ? "cron secret" : wrapper === "withAuth" ? "session" : `same as ${wrapper}`;
    const schemas = [...new Set([...src.matchAll(/(\w+(?:Schema|Query|query|body))\.parse/g)].map((x) => x[1]))];
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push({ method: m[2], route, auth, doc, schemas });
    count++;
  }
}

let out = `# API reference

${files.length} route files · ${count} handlers. _Generated by \`node scripts/gen-api-docs.mjs\` — do not edit by hand._

## Conventions

- Every handler is created by \`withAuth\`, \`withPublic\` or \`withCron\` (\`lib/api/route.ts\`). \`tests/unit/route-guard.test.ts\` fails if one isn't, and keeps the public allowlist explicit.
- Success: \`{ "success": true, "data": …, "message"?: string }\`. Error: \`{ "success": false, "error": { "code", "message", "details"?: [{ "path", "message" }] } }\`.
- Status codes: 400 validation (field \`details\`), 401 not signed in, 404 not found or not yours, 409 conflict (\`VERSION_CONFLICT\`, \`RECONCILED_CHANGE\`, \`IDEMPOTENCY_KEY_REUSED\`), 413 too large, 422 business rule (specific \`code\`), 429 rate limited, 503 dependency unavailable.
- Browser mutations must be same-origin (CSRF check in \`withAuth\`).
- Money: numbers or numeric strings, at most 2 decimals. Financial dates: \`YYYY-MM-DD\` calendar dates in the user's time zone. Ranges are start-inclusive / end-exclusive internally; query \`endDate\` values are inclusive.
- Creates accept an \`Idempotency-Key\` header: a retry with the same key and body replays the first result; the same key with a different body is 409.
- Edits carry the \`version\` they were based on; a stale version is 409 \`VERSION_CONFLICT\`.
- Validators live in \`lib/validation/schemas.ts\` and are shared with the forms.
`;
for (const [group, rows] of [...groups.entries()].sort()) {
  out += `\n## ${group}\n\n| Method | Path | Auth | Validates | Notes |\n|---|---|---|---|---|\n`;
  for (const r of rows) {
    out += `| ${r.method} | \`${r.route}\` | ${r.auth} | ${r.schemas.map((s) => `\`${s}\``).join(", ")} | ${r.doc.replace(/\|/g, "\\|")} |\n`;
  }
}
writeFileSync("docs/API.md", out);
console.log(`docs/API.md: ${files.length} route files, ${count} handlers`);
